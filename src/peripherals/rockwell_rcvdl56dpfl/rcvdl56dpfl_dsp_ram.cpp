void Rcvdl56dpflDspRam::PowerOn() {
    words_.fill(0u);
    for (const PowerOnWord& w : kPowerOnWords) words_[w.code] = w.value;
}

void Rcvdl56dpflDspRam::Write(uint32_t code, uint16_t word) {
    words_[code] = word;
}

uint16_t Rcvdl56dpflDspRam::Read(uint32_t code) const {
    const bool pair_low = std::find(std::begin(kPairLowCodes), std::end(kPairLowCodes), code) !=
                          std::end(kPairLowCodes);
    if (pair_low) return static_cast<uint16_t>((Byte(code + 1u) << 8) | Byte(code));
    return words_[code];
}

void Rcvdl56dpflDspRam::ApplyNewConfiguration(uint8_t conf, bool guard_tone_550, bool compromise_equalizer) {
    if (guard_tone_550)
        words_[kGuardToneLevel] = compromise_equalizer ? kGuardTone550Ceq : kGuardTone550;
    else
        words_[kGuardToneLevel] = compromise_equalizer ? kGuardTone1800Ceq : kGuardTone1800;
    ResetToPowerOnValue(kFskTransmitGain);
    for (uint32_t code : kAnswerToneCodes) ResetToPowerOnValue(code);
    if (conf == kConfV8)
        for (uint32_t code : kV8StatusCodes) words_[code] = 0u;
}

void Rcvdl56dpflDspRam::ApplyDtrOff() {
    for (uint32_t code : kAnswerToneCodes) ResetToPowerOnValue(code);
}

bool Rcvdl56dpflDspRam::MemoryAccessNewsMasked() const {
    return (Byte(kMaskControlCode) & kMaskMemoryAccess) != 0u;
}

uint8_t Rcvdl56dpflDspRam::StatusChangeMask(uint32_t reg) const {
    if (reg == kRegConf) return (Byte(kMaskControlCode) & kMaskConfChange) ? kAllBits : 0u;
    for (const StatusMaskCode& m : kStatusMaskCodes)
        if (m.reg == reg) return Byte(m.code);
    return 0u;
}

void Rcvdl56dpflDspRam::SaveState(StateWriter& w) const {
    w.Write("ram", words_);
}

void Rcvdl56dpflDspRam::RestoreState(StateReader& r) {
    r.Read("ram", words_);
}

void Rcvdl56dpflDspRam::ResetToPowerOnValue(uint32_t code) {
    words_[code] = 0u;
    for (const PowerOnWord& w : kPowerOnWords)
        if (w.code == code) words_[code] = w.value;
}

